"""Console installation resources must ship in the literal apps tree."""
import hashlib
import importlib.util
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'apps/ddnsto'


class AppsSiteTest(unittest.TestCase):
    def test_public_ddnsto_contains_only_runtime_artifacts(self):
        for relative in ['source', 'app.json', 'README.md', 'ddnsto-install/current/review.json']:
            self.assertFalse((APP / relative).exists(), f'non-runtime material: {relative}')
        self.assertTrue((ROOT / 'sources/ddnsto/app.json').is_file())
        self.assertTrue((ROOT / 'sources/ddnsto/templates/install.ps1.in').is_file())

    def test_public_checker_rejects_accidental_source_upload(self):
        with tempfile.TemporaryDirectory() as directory:
            apps = Path(directory) / 'apps'
            (apps / 'ddnsto/source').mkdir(parents=True)
            (apps / 'ddnsto/source/template.in').write_text('not for publication')
            result = subprocess.run([sys.executable, '-B', str(ROOT / 'scripts/check-public-tree.py'), str(apps)],
                                    capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)

    def test_build_checks_generated_files_and_preserves_history(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name in ['apps', 'scripts', 'lib', 'templates', 'sources']:
                shutil.copytree(ROOT / name, root / name,
                                ignore=shutil.ignore_patterns('__pycache__'))
            command = [sys.executable, '-B', str(root / 'scripts/build.py')]
            def run(*flags):
                return subprocess.run(command + list(flags), capture_output=True, text=True)
            self.assertEqual(run('--check').returncode, 0)
            alias = root / 'apps/ddnsto/i.ps1'
            alias.unlink()
            self.assertNotEqual(run('--check').returncode, 0)
            self.assertEqual(run().returncode, 0)
            self.assertEqual(run('--check').returncode, 0)
            history = b'previous reviewed installer\n'
            history_digest = hashlib.sha256(history).hexdigest()
            history_path = root / f'apps/ddnsto/ddnsto-install/current/immutable/{history_digest}/install.sh'
            history_path.parent.mkdir(parents=True)
            history_path.write_bytes(history)
            self.assertEqual(run().returncode, 0)
            self.assertEqual(history_path.read_bytes(), history)
            self.assertIn(history_digest, (root / 'apps/SHA256SUMS').read_text())
            # Detect changed generated bytes, not merely missing filenames.
            alias.write_bytes(b'wrong PowerShell entry')
            self.assertNotEqual(run('--check').returncode, 0)
            self.assertEqual(run().returncode, 0)
            current = root / 'apps/ddnsto/ddnsto-install/current'
            payload = next((current / 'immutable').glob('*/install.ps1'))
            payload.write_bytes(b'corrupted body')
            self.assertNotEqual(run().returncode, 0)

    def test_unexpanded_template_cannot_be_published(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name in ['apps', 'scripts', 'lib', 'templates', 'sources']:
                shutil.copytree(ROOT / name, root / name,
                                ignore=shutil.ignore_patterns('__pycache__'))
            template = root / 'sources/ddnsto/recommended-entry.ps1'
            template.write_text(template.read_text() + '\n# @@UNRESOLVED@@\n')
            result = subprocess.run([sys.executable, '-B', str(root / 'scripts/build.py')],
                                    capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('unresolved', result.stderr)

    def test_local_publication_transaction_preserves_digest_files(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            apps = root / 'apps'
            shutil.copytree(ROOT / 'apps', apps)
            live = root / 'live'
            live.mkdir()
            environment = dict(os.environ, ZSETUP_PUBLISH_ALLOW_UNVERSIONED='1')
            def run(action):
                result = subprocess.run(['sh', str(ROOT / 'scripts/publish.sh'), action,
                                         str(apps), str(live)], env=environment,
                                        capture_output=True, text=True)
                self.assertEqual(result.returncode, 0, result.stderr)
            run('stage')
            body = next((apps / 'ddnsto/ddnsto-install/current/immutable').glob('*/install.ps1'))
            target = live / body.relative_to(apps)
            self.assertEqual(target.read_bytes(), body.read_bytes())
            self.assertFalse((live / 'ddnsto/i.ps1').exists())
            run('activate')
            self.assertEqual((live / 'ddnsto/i.ps1').read_bytes(), (APP / 'i.ps1').read_bytes())
            run('verify')
            run('rollback')
            self.assertTrue(target.is_file())
            self.assertFalse((live / 'ddnsto/i.ps1').exists())

    def test_complete_console_site_is_committed_build_output(self):
        for extension, platform in [('sh', 'shell'), ('ps1', 'powershell')]:
            alias = APP / ('i' if extension == 'sh' else 'i.ps1')
            self.assertTrue(alias.is_file(), f'missing deployable entry: {alias}')
            current = APP / 'ddnsto-install/current'
            self.assertEqual(alias.read_bytes(), (current / f'recommended-entry.{extension}').read_bytes())
            body = alias.read_text(encoding='utf-8-sig')
            self.assertIn('https://run.ddnsto.com/ddnsto-install/current', body)
            self.assertNotIn('@@', body)
            self.assertNotIn('install.ddnsto.com', body)
            header, digest, size = (current / f'recommended-{platform}.txt').read_text().splitlines()
            self.assertEqual(header, f'ddnsto-recommendation-v1-{platform}')
            payload = (current / f'immutable/{digest}/install.{extension}').read_bytes()
            self.assertEqual(hashlib.sha256(payload).hexdigest(), digest)
            self.assertEqual(len(payload), int(size))
        guide = APP / 'ddnsto-install/agent/install.md'
        self.assertIn('https://run.ddnsto.com/i', guide.read_text())
        self.assertNotIn('install.ddnsto.com', guide.read_text())

    def test_deployment_stages_digest_bodies_before_entries(self):
        spec = importlib.util.spec_from_file_location('publish_apps', ROOT / 'scripts/publish-apps.py')
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        digest = 'a' * 64
        for path in [f'ddnsto/ddnsto-install/current/immutable/{digest}/install.ps1',
                     f'ddnsto/ddnsto-install/agent/versions/{digest}/install.md']:
            self.assertTrue(module.is_immutable(path), path)
        self.assertFalse(module.is_immutable('ddnsto/i.ps1'))
        self.assertFalse(module.is_immutable('ddnsto/ddnsto-install/current/recommended-shell.txt'))


if __name__ == '__main__':
    unittest.main()
